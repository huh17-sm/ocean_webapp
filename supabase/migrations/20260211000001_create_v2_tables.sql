-- 1. debriefings 테이블 (상세 디브리핑)
-- reservations 테이블과 1:1 관계 (하나의 예약에 하나의 디브리핑)
CREATE TABLE IF NOT EXISTS public.debriefings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id UUID NOT NULL REFERENCES public.reservations(id) ON DELETE CASCADE,
    instructor_id UUID NOT NULL REFERENCES public.profiles(id),
    performance TEXT, -- 수행 평가
    improvement TEXT, -- 개선 포인트
    strengths TEXT,   -- 잘한 점
    next_goal TEXT,   -- 다음 목표
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE(reservation_id)
);

-- RLS 활성화
ALTER TABLE public.debriefings ENABLE ROW LEVEL SECURITY;

-- 24. Policies for debriefings
DROP POLICY IF EXISTS "Users can view their own debriefings" ON public.debriefings;
CREATE POLICY "Users can view their own debriefings" ON public.debriefings
    FOR SELECT USING (
        auth.uid() IN (
            SELECT user_id FROM public.reservations WHERE id = debriefings.reservation_id
        ) OR 
        EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role IN ('instructor', 'admin'))
    );

DROP POLICY IF EXISTS "Instructors and Admins can insert/update debriefings" ON public.debriefings;
CREATE POLICY "Instructors and Admins can insert/update debriefings" ON public.debriefings
    FOR ALL USING (
        EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role IN ('instructor', 'admin'))
    );

-- 39. course_progress tables
CREATE TABLE IF NOT EXISTS public.course_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    course_level TEXT NOT NULL, -- 입문/초급/중급/고급
    status TEXT NOT NULL DEFAULT 'in_progress' CHECK (status IN ('in_progress', 'completed', 'dropped')),
    theory_completed BOOLEAN DEFAULT false,
    pool_sessions_completed INTEGER DEFAULT 0,
    started_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    completed_at TIMESTAMP WITH TIME ZONE,
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE(user_id, course_level)
);

ALTER TABLE public.course_progress ENABLE ROW LEVEL SECURITY;

