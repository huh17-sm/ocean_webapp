-- 70. skill_completions 테이블 (스킬 체크리스트)
CREATE TABLE IF NOT EXISTS public.skill_completions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    course_level TEXT NOT NULL, -- 입문/초급/중급/고급
    skill_type TEXT NOT NULL,   -- static, dynamic, depth, rescue, theory
    is_completed BOOLEAN DEFAULT false,
    completed_at TIMESTAMP WITH TIME ZONE,
    completed_by UUID REFERENCES public.profiles(id), -- 확인한 강사
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE(user_id, course_level, skill_type)
